#!/usr/bin/env python3
"""Generate native agent definitions from the shared Markdown role sources."""

import argparse
import json
from pathlib import Path
import sys

from common import read_document

ROOT = Path(__file__).resolve().parents[1]


def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(root: Path) -> dict[str, str]:
    manifest = json.loads((root / "harness.json").read_text(encoding="utf-8"))
    files = {}
    for name in manifest["agents"]:
        fields, body = read_document(root / "agents" / f"{name}.md")
        if fields.keys() != {"name", "description"} or fields["name"] != name:
            raise ValueError(f"Invalid role metadata: {name}")
        files[f"adapters/codex/agents/{name}.toml"] = (
            f"# Generated by scripts/render_agents.py from agents/{name}.md\n"
            f"name = {quote(name)}\n"
            f"description = {quote(fields['description'])}\n"
            f"developer_instructions = {quote(body)}\n"
        )
        files[f"adapters/claude/agents/{name}.md"] = (
            f"---\nname: {quote(name)}\ndescription: {quote(fields['description'])}\n"
            'tools: "Read, Grep, Glob"\nmodel: "inherit"\n---\n\n'
            f"<!-- Generated by scripts/render_agents.py from agents/{name}.md -->\n\n{body}"
        )
    return files


def check(root: Path) -> list[str]:
    expected = render(root)
    stale = [name for name, content in expected.items()
             if not (root / name).is_file() or (root / name).read_text(encoding="utf-8") != content]
    existing = {path.relative_to(root).as_posix() for path in (root / "adapters").glob("*/agents/*")
                if path.is_file()}
    return sorted(set(stale) | (existing - expected.keys()))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        stale = check(ROOT)
        if stale:
            print(f"Stale agent adapters: {', '.join(stale)}", file=sys.stderr)
            return 1
        print("Agent adapters match their sources")
    else:
        for name, content in render(ROOT).items():
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        print("Generated 6 native agent definitions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
